# 📘 Escape Sequence Characters in Python

# Escape sequences are special characters used with backslash (\)

# 1. \n → New Line
print("Hello\nWorld")
# Output:
# Hello
# World

# 2. \t → Tab Space
print("Hello\tWorld")
# Output: Hello    World

# 3. \\ → Backslash
print("Hello\\World")
# Output: Hello\World

# 4. \' → Single Quote
print('It\'s Python')
# Output: It's Python

# 5. \" → Double Quote
print("He said \"Hello\"")
# Output: He said "Hello"

# 6. \r → Carriage Return
print("Hello\rWorld")
# Output: World

# 7. \b → Backspace
print("Hello\bWorld")
# Output: HellWorld

# 8. \f → Form Feed
print("Hello\fWorld")

# 9. \ooo → Octal value
print("\110\145\154\154\157")
# Output: Hello

# 10. \xhh → Hex value
print("\x48\x65\x6c\x6c\x6f")
# Output: Hello